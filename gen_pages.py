def gen_sitemap():
    from datetime import date as _date
    today = _date.today().isoformat()
    urls = []
    for path in PAGES:
        loc = SITE_URL + "/" + path
        # priority 口径与 build_articles.py 的 sitemap_priority() 保持一致
        if path == "":
            pri = "1.0"
        elif path in ("feiyong/", "liucheng/", "articles/"):
            pri = "0.8"
        else:
            pri = "0.7"
        # 首页更新最频繁；攻略枢纽按日更；其余内容页实际修订频率低，写 monthly 更诚实
        if path == "":
            freq = "weekly"
        elif path == "articles/":
            freq = "daily"
        else:
            freq = "monthly"
        urls.append(
            f"  <url>\n    <loc>{loc}</loc>\n    <lastmod>{today}</lastmod>\n"
            f"    <changefreq>{freq}</changefreq>\n    <priority>{pri}</priority>\n  </url>"
        )
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           + "\n".join(urls) + "\n</urlset>\n")
    write("sitemap.xml", xml)

    robots = f"""User-agent: *
Allow: /

# 站长平台验证文件对搜索无价值，不必抓取
Disallow: /verify-baidu.txt
Disallow: /baidu_verify_

Sitemap: {SITE_URL}/sitemap.xml
"""
    write("robots.txt", robots)


